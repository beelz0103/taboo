#!/usr/bin/env node
"use strict";
const fs=require("fs"),vm=require("vm"),path=require("path");
const {curate}=require("./curate-japanese-engine");
const input=process.argv[2]||path.join(__dirname,"..","japanese-master-source.js");
const output=process.argv[3]||path.join(__dirname,"..","japanese-master.js");
const limit=Number(process.argv[4]||3000),context={window:{}};
vm.runInNewContext(fs.readFileSync(input,"utf8"),context,{filename:input});
if(!Array.isArray(context.window.ANKI_DECK_JA))throw Error("ANKI_DECK_JA not found in "+input);
const cards=curate(context.window.ANKI_DECK_JA,limit);
const body="/* Generated by tools/curate-japanese-master.js. Edit via /curate. */\nwindow.ANKI_DECK_JA=[\n"+cards.map(JSON.stringify).join(",\n")+"\n];\n";
fs.writeFileSync(output,body);
console.log(`curated ${context.window.ANKI_DECK_JA.length} source cards down to ${cards.length} in ${output}`);
